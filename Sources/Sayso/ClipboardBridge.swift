import AppKit

/// For apps that tell assistive software nothing about their text: Sayso asks the app itself to Copy (to read the
/// selection) or Paste (to replace it) through the app's own Edit menu, and then puts the clipboard back exactly
/// as it was. No key presses are faked.
///
/// The clipboard is left alone entirely when it holds something from a password manager, when its contents can't
/// be saved in full, or when the app is a password manager.
@MainActor
enum ClipboardBridge {
    /// Tests name a pasteboard of their own (SAYSO_TEST_PASTEBOARD), so the real clipboard is never touched.
    static let pasteboard: NSPasteboard = ProcessInfo.processInfo.environment["SAYSO_TEST_PASTEBOARD"]
        .map { NSPasteboard(name: NSPasteboard.Name($0)) } ?? .general

    // Conventions clipboard managers follow (nspasteboard.org).
    private static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let fileURL = NSPasteboard.PasteboardType("public.file-url")

    private static let passwordManagers: Set<String> = [
        "com.apple.Passwords", "com.apple.keychainaccess", "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "com.lastpass.LastPass", "org.keepassxc.keepassxc", "com.dashlane.dashlanephonefinal",
        "in.sinew.Enpass-Desktop", "com.sibersystems.RoboForm", "me.proton.pass.electron", "com.nordpass.macos.nordpass",
    ]

    private(set) static var busy = false
    /// Why the last attempt did nothing, for the event log.
    private(set) static var lastReport = ""

    // MARK: Saving and restoring

    struct Snapshot {
        fileprivate let items: [[(type: NSPasteboard.PasteboardType, data: Data)]]
    }

    /// Everything on the clipboard, in every format; nil if any of it can't be read back (then nothing is touched).
    static func snapshot() -> Snapshot? {
        var total = 0
        var items: [[(type: NSPasteboard.PasteboardType, data: Data)]] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var entries: [(type: NSPasteboard.PasteboardType, data: Data)] = []
            for type in item.types {
                guard let data = item.data(forType: type) else { return nil }
                total += data.count
                if total > 100_000_000 { return nil }
                entries.append((type, data))
            }
            items.append(entries)
        }
        return Snapshot(items: items)
    }

    /// Puts a snapshot back, item for item and format for format.
    static func restore(_ snapshot: Snapshot) {
        pasteboard.clearContents()
        guard !snapshot.items.isEmpty else { return }
        let items = snapshot.items.map { entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for entry in entries { item.setData(entry.data, forType: entry.type) }
            return item
        }
        pasteboard.writeObjects(items)
    }

    /// Something a password manager put there (they also clear it on a timer, which a change would defeat).
    static var holdsSecret: Bool {
        let types = pasteboard.types ?? []
        return types.contains(concealed) || types.contains(transient)
    }

    // MARK: The app's own Copy and Paste commands

    /// The app's menu command with the shortcut ⌘<key> (⌘C is Copy, ⌘V is Paste, whatever the menus are called).
    private static func menuItem(pid: pid_t, key: String) -> AXUIElement? {
        func children(_ element: AXUIElement) -> [AXUIElement] {
            var value: CFTypeRef?
            AXUIElementCopyAttributeValue(element, kAXChildrenAttribute as CFString, &value)
            return value as? [AXUIElement] ?? []
        }
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, 0.5)
        var bar: CFTypeRef?
        guard AXUIElementCopyAttributeValue(app, kAXMenuBarAttribute as CFString, &bar) == .success, let bar,
              CFGetTypeID(bar) == AXUIElementGetTypeID() else { return nil }
        // Skip the Apple menu; Edit is usually the third after it.
        for title in children(bar as! AXUIElement).dropFirst().prefix(8) {
            for menu in children(title) {
                for item in children(menu) {
                    var char: CFTypeRef?
                    AXUIElementCopyAttributeValue(item, kAXMenuItemCmdCharAttribute as CFString, &char)
                    guard (char as? String)?.uppercased() == key else { continue }
                    var modifiers: CFTypeRef?
                    AXUIElementCopyAttributeValue(item, kAXMenuItemCmdModifiersAttribute as CFString, &modifiers)
                    if (modifiers as? Int ?? 0) == 0 { return item }
                }
            }
        }
        return nil
    }

    private static func isEnabled(_ item: AXUIElement) -> Bool {
        var value: CFTypeRef?
        AXUIElementCopyAttributeValue(item, kAXEnabledAttribute as CFString, &value)
        return value as? Bool ?? false
    }

    @discardableResult
    private static func press(_ item: AXUIElement) -> Bool {
        AXUIElementPerformAction(item, kAXPressAction as CFString) == .success
    }

    /// Calls `done` once the clipboard changes from `count`, or with false after `timeout`.
    private static func waitForChange(from count: Int, timeout: TimeInterval, done: @escaping @MainActor (Bool) -> Void) {
        let deadline = Date().addingTimeInterval(timeout)
        @MainActor func check() {
            if pasteboard.changeCount != count { done(true) }
            else if Date() > deadline { done(false) }
            else { DispatchQueue.main.asyncAfter(deadline: .now() + 0.02, execute: check) }
        }
        check()
    }

    // MARK: Reading a selection by copying

    struct Copied {
        let text: String
        /// The app would accept a paste where the selection is, so it is most likely an editable field.
        let editable: Bool
    }

    /// Whether copying may be tried in this app at all.
    private static func allowed(bundleID: String?, focusedRole: String) -> Bool {
        if let bundleID, passwordManagers.contains(bundleID) { lastReport = "password manager"; return false }
        if focusedRole == "AXSecureTextField" { lastReport = "password field"; return false }
        if holdsSecret { lastReport = "clipboard holds a password-manager item"; return false }
        return true
    }

    /// Asks the app to copy its selection, hands back the text, and restores the clipboard.
    static func copySelection(pid: pid_t, bundleID: String?, focusedRole: String, completion: @escaping @MainActor (Copied?) -> Void) {
        lastReport = ""
        guard !busy else { lastReport = "busy"; completion(nil); return }
        guard allowed(bundleID: bundleID, focusedRole: focusedRole) else { completion(nil); return }
        guard let copy = menuItem(pid: pid, key: "C") else { lastReport = "no Copy command"; completion(nil); return }
        guard let saved = snapshot() else { lastReport = "clipboard can't be saved"; completion(nil); return }
        busy = true
        let before = pasteboard.changeCount
        press(copy)
        waitForChange(from: before, timeout: 0.4) { changed in
            guard changed else { busy = false; lastReport = "nothing was copied"; completion(nil); return }
            let after = pasteboard.changeCount
            let types = pasteboard.types ?? []
            var copied: Copied?
            if types.contains(concealed) {
                lastReport = "the app marked its copy as secret"
            } else if types.contains(fileURL) {
                lastReport = "files, not text"
            } else if let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !text.isEmpty {
                copied = Copied(text: text, editable: menuItem(pid: pid, key: "V").map(isEnabled) ?? false)
                lastReport = "copied"
            } else {
                lastReport = "no text in what was copied"
            }
            // Put the user's clipboard back, unless something else has changed it since.
            if pasteboard.changeCount == after { restore(saved) }
            busy = false
            completion(copied)
        }
    }

    // MARK: Replacing a selection by pasting

    /// Pastes `text` over the selection in the app, then restores the clipboard. `stillSelected` says whether the
    /// original text is still selected (checked right before pasting); `changed` whether the paste has landed.
    static func paste(_ text: String, pid: pid_t, stillSelected: @MainActor (@escaping @MainActor (Bool) -> Void) -> Void,
                      changed: (@MainActor () -> Bool)?, completion: @escaping @MainActor (Bool) -> Void) {
        lastReport = ""
        guard !busy else { lastReport = "busy"; completion(false); return }
        guard !holdsSecret else { lastReport = "clipboard holds a password-manager item"; completion(false); return }
        guard let pasteItem = menuItem(pid: pid, key: "V") else { lastReport = "no Paste command"; completion(false); return }
        stillSelected { same in
            guard same else { lastReport = "the selection changed"; completion(false); return }
            guard let saved = snapshot() else { lastReport = "clipboard can't be saved"; completion(false); return }
            busy = true
            pasteboard.clearContents()
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            item.setData(Data(), forType: transient)
            item.setData(Data(), forType: autoGenerated)
            pasteboard.writeObjects([item])
            let mine = pasteboard.changeCount
            guard isEnabled(pasteItem), press(pasteItem) else {
                if pasteboard.changeCount == mine { restore(saved) }
                busy = false
                lastReport = "Paste isn't available there"
                completion(false)
                return
            }
            // Web-based apps read the clipboard a moment after the command, so it stays put for a while: until
            // the text is seen to change (plus a margin), or for a second if that can't be observed.
            let started = Date()
            @MainActor func finish() {
                let elapsed = Date().timeIntervalSince(started)
                let landed = changed?() ?? false
                if (landed && elapsed >= 0.3) || elapsed >= 1.0 {
                    if pasteboard.changeCount == mine { restore(saved) }
                    busy = false
                    lastReport = landed || changed == nil ? "pasted" : "pasted (not confirmed)"
                    completion(true)
                } else {
                    DispatchQueue.main.asyncAfter(deadline: .now() + 0.05, execute: finish)
                }
            }
            finish()
        }
    }

    /// Whether `original` is still what's selected, found out by copying (for apps that can't be asked directly).
    static func selectionMatches(_ original: String, pid: pid_t, bundleID: String?, done: @escaping @MainActor (Bool) -> Void) {
        copySelection(pid: pid, bundleID: bundleID, focusedRole: "") { copied in
            done(copied?.text == original.trimmingCharacters(in: .whitespacesAndNewlines))
        }
    }
}
